//! Player names: a whitelist of characters (no invisible, format, private-use
//! or look-alike filler characters), a cap on stacked marks, and a
//! confusable-folded key so look-alike names get a `#n` suffix.

/// Name characters: 0 = dropped, 1 = base character, 2 = combining mark,
/// 3 = space, 4 = emoji presentation selector, 5 = zero width joiner (only
/// between two emoji), 6 = keycap mark. A whitelist of letters, digits,
/// punctuation and symbols of common scripts.
pub fn name_char_class(c: u32) -> u8 {
    if nfc_unstable(c) {
        // canonical twins of other characters (CJK compatibility ideographs,
        // Indic nukta letters, U+037E ';'): never written so after NFC
        return 0;
    }
    match c {
        0x20 | 0xA0 | 0x2000..=0x200A | 0x205F | 0x3000 => 3,
        0x22 | 0x26 | 0x27 | 0x3C | 0x3E | 0x5C | 0x60 => 0, // " & ' < > \ `
        0x21..=0x7E => 1,
        0xA1..=0xAC | 0xAE..=0x2AF => 1,          // Latin-1 (no soft hyphen), Latin ext., IPA
        0x300..=0x36F => 2,                         // combining diacritics
        0x370..=0x377 | 0x37A..=0x37F | 0x384..=0x38A | 0x38C | 0x38E..=0x3A1 | 0x3A3..=0x3FF => 1, // Greek
        0x400..=0x482 | 0x48A..=0x52F => 1,         // Cyrillic
        0x483..=0x489 => 2,
        0x531..=0x556 | 0x561..=0x587 => 1,         // Armenian
        0x591..=0x5BD | 0x5BF | 0x5C1..=0x5C2 | 0x5C4..=0x5C5 | 0x5C7 => 2, // Hebrew points
        0x5D0..=0x5EA => 1,
        0x620..=0x64A | 0x660..=0x669 | 0x671..=0x6D3 => 1, // Arabic
        0x64B..=0x65F | 0x670 => 2,
        0x900..=0x903 | 0x93A..=0x93C | 0x93E..=0x94F | 0x951..=0x957 | 0x962..=0x963 => 2, // Devanagari signs
        0x904..=0x939 | 0x93D | 0x950 | 0x958..=0x961 | 0x964..=0x97F => 1,
        0x980..=0xD7F | 0x10A0..=0x10FF => name_class_extra(c), // Indic scripts, Georgian
        0xE31 | 0xE34..=0xE3A | 0xE47..=0xE4E => 2, // Thai marks
        0xE01..=0xE30 | 0xE32..=0xE33 | 0xE3F..=0xE46 | 0xE4F..=0xE5B => 1,
        0x1E00..=0x1EFF => 1,                       // Latin extended additional (Vietnamese)
        0x200D => 5,
        0x2010..=0x2027 | 0x2030..=0x205E => 1,     // punctuation (no separators / bidi / invisible)
        0x2070..=0x2071 | 0x2074..=0x208E | 0x2090..=0x209C => 1,
        0x20A0..=0x20C0 => 1,                       // currency
        0x20E3 => 6,
        // ℃ ℉ № ™ only: other letterlike symbols and the Roman numerals look like letters
        0x2103 | 0x2109 | 0x2116 | 0x2122 => 1,
        // arrows, technical, enclosed, boxes, shapes, symbols, dingbats, math
        // (not Braille: U+2800 is a blank)
        0x2190..=0x23FF | 0x2460..=0x27FF | 0x2900..=0x2BFF => 1,
        0x302A..=0x302F | 0x3099..=0x309A => 2,
        0x3001..=0x3029 | 0x3030..=0x303F => 1,     // CJK punctuation
        0x3041..=0x3096 | 0x309B..=0x30FF => 1,     // kana
        // Hangul compatibility jamo (no filler), kanbun, katakana extensions;
        // not Bopomofo or CJK strokes, which copy kana and kanji
        0x3131..=0x3163 | 0x3165..=0x318E | 0x3190..=0x319F | 0x31F0..=0x31FF => 1,
        // CJK and Hangul; not the radicals or compatibility ideographs, which
        // look exactly like unified ideographs
        0x3200..=0x4DBF | 0x4DC0..=0x9FFF | 0xAC00..=0xD7A3 | 0xFE30..=0xFE4F => 1,
        0xFE0F => 4,
        0xFF01..=0xFF5E | 0xFF61..=0xFF9F | 0xFFE0..=0xFFEE => 1, // full/halfwidth (no halfwidth filler)
        0x1F3FB..=0x1F3FF => 2,                     // emoji skin tones modify the previous emoji
        0x1F000..=0x1FAFF => 1,                     // emoji and symbols
        0x20000..=0x2F7FF => 1,                     // CJK extensions (not the compatibility supplement)
        _ => 0,
    }
}

fn is_emoji(c: u32) -> bool {
    matches!(c, 0x1F000..=0x1FAFF | 0x2600..=0x27BF | 0x2190..=0x21FF | 0x2300..=0x23FF | 0x2B00..=0x2BFF | 0x3030 | 0x303D | 0xA9 | 0xAE | 0x2122)
}

/// At most this many combining marks per base character (accents, Thai and
/// Indic vowel signs), so names cannot stack marks into the rows above.
const NAME_MARKS: u32 = 2;
/// Base characters (and spaces) kept.
const NAME_LEN: usize = 14;

pub fn sanitize_name(raw: &[u8], fallback: &str) -> String {
    let s = String::from_utf8_lossy(raw);
    let chars: Vec<char> = s.chars().collect();
    let mut out = String::new();
    let mut count = 0;
    let mut last_space = true;
    let mut marks = NAME_MARKS; // no base character yet: no marks allowed
    let mut prev: u32 = 0; // last base character kept (0 = none / a space)
    let mut vs = false; // an emoji presentation selector follows `prev` already
    for (k, &ch) in chars.iter().enumerate() {
        let c = ch as u32;
        match name_char_class(c) {
            1 => {
                out.push(ch);
                last_space = false;
                marks = 0;
                prev = c;
                vs = false;
            }
            2 => {
                if marks < NAME_MARKS {
                    out.push(ch);
                    marks += 1;
                }
                continue;
            }
            3 => {
                if last_space {
                    continue;
                }
                out.push(' ');
                last_space = true;
                marks = NAME_MARKS;
                prev = 0;
            }
            4 => {
                // emoji presentation (❤️, 1️⃣): once, right after a symbol or keycap base
                if !vs && (is_emoji(prev) || matches!(prev, 0x23 | 0x2A | 0x30..=0x39)) && marks == 0 {
                    out.push(ch);
                    vs = true;
                }
                continue;
            }
            5 => {
                // zero width joiner: only inside an emoji sequence (👨‍👩‍👧)
                let next = chars.get(k + 1).map_or(0, |n| *n as u32);
                if is_emoji(prev) && is_emoji(next) && count < NAME_LEN {
                    out.push(ch);
                }
                continue;
            }
            6 => {
                if matches!(prev, 0x23 | 0x2A | 0x30..=0x39) && marks == 0 {
                    out.push(ch);
                    marks = NAME_MARKS;
                }
                continue;
            }
            _ => continue,
        }
        count += 1;
        if count >= NAME_LEN {
            break;
        }
    }
    // a joiner may not end the name
    while out.ends_with('\u{200D}') {
        out.pop();
    }
    let t = out.trim().to_string();
    if t.is_empty() {
        fallback.to_string()
    } else {
        t
    }
}

/// Comparison key for duplicate names: compatibility twins folded (NFKC:
/// 'µ' as 'μ', '…' as '...', '℃' as '°C'); marks, emoji selectors and
/// joiners removed; precomposed letters reduced to their base (NFC 'é' and
/// NFD 'é' alike); case folded; fullwidth and halfwidth forms folded; voiced
/// kana folded; Greek, Cyrillic, Armenian, Hebrew and Arabic look-alikes
/// (capitals and small letters) mapped to Latin or to one another ('Π' and
/// 'П', 'З' and '3'), and kanji / hiragana / jamo look-alikes to katakana
/// ('力' as 'カ', '一' and 'ㅡ' as 'ー'); 'l', 'I', '1' and
/// '|' (and 'O' / '0') merged; 'rn' read as 'm' and 'vv' as 'w'. So 'Kaze',
/// 'Ｋａｚｅ', 'Kаze' (Cyrillic a) and 'ΚΑΖΕ' all count as the same name.
pub fn name_key(name: &str) -> String {
    let mut k = String::new();
    let mut push = |c: char| {
        let c = match c {
            'l' | '1' | '|' => 'i',
            '0' => 'o',
            c => c,
        };
        k.push(c);
    };
    let mut buf = [0u8; 4];
    for ch0 in name.chars() {
        let seq: &str = match compat_fold(ch0 as u32) {
            Some(s) => s,
            None => ch0.encode_utf8(&mut buf),
        };
        for ch in seq.chars() {
            let mut c = ch as u32;
            if name_char_class(c) >= 2 && name_char_class(c) != 3 {
                continue;
            }
            if (0xFF01..=0xFF5E).contains(&c) {
                c -= 0xFEE0;
            }
            if matches!(c, 0xFF9E | 0xFF9F | 0x309B | 0x309C) {
                continue; // spacing (semi-)voiced sound marks: folded like the voicing
            }
            if let Some(f) = fold_halfwidth_kana(c) {
                c = f as u32;
            }
            if let Some(f) = fold_voiced_kana(c) {
                c = f as u32;
            }
            let ch = char::from_u32(c).unwrap_or(ch);
            // the letter as written (capital Η is H-like, small η n-like) ...
            let base = strip_marks(c).unwrap_or(ch);
            if let Some(s) = look_alike(base as u32) {
                s.chars().for_each(&mut push);
                continue;
            }
            // ... then in lowercase
            for lc in base.to_lowercase() {
                let lb = strip_marks(lc as u32).unwrap_or(lc);
                match look_alike(lb as u32) {
                    Some(s) => s.chars().for_each(&mut push),
                    None => push(lb),
                }
            }
        }
    }
    k.replace("rn", "m").replace("vv", "w")
}

